function rotateOptions(values: string[], correctIndexes: number[], seed: number) {
  const offset = Math.abs(seed) % values.length;
  const rotated = [...values.slice(offset), ...values.slice(0, offset)];
  return {
    options: rotated.map((text, index): GeneratedOption => ({ id: OPTION_IDS[index], text })),
    correctIndexes: correctIndexes.map((index) => (index - offset + values.length) % values.length),
  };
}

function bankFor(sectionName: string) {
  const lower = sectionName.toLowerCase();
  if (lower.includes("aptitude")) return GENERAL_APTITUDE;
  if (lower.includes("mathematics") || lower.includes("math")) return ENGINEERING_MATHEMATICS;
  return COMPUTER_SCIENCE;
}

export function buildGateQuestions(
  sectionName: string,
  count: number,
  marks: number,
  negativeMarks: number,
  startNumber: number,
  seed: number,
  questionMarks?: number[],
): GeneratedQuestion[] {
  const bank = bankFor(sectionName);

  return Array.from({ length: count }, (_, index) => {
    const template = bank[(seed * 37 + index * 11 + sectionName.length) % bank.length];
    const questionMarksValue = questionMarks?.[index] ?? marks;
    const isObjective = template.kind !== "nat";

    if (!isObjective) {
      return {
        questionNumber: startNumber + index,
        text: template.text,
        options: [],
        correctOptionId: null,
        correctOptionIds: [],
        correctNumericalAnswer: template.answer ?? 0,
        numericalTolerance: template.tolerance ?? 0.01,
        type: "NUMERICAL",
        explanation: template.explanation,
        subjectTag: sectionName,
        topicTag: template.topic,
        marks: questionMarksValue,
        negativeMarks: 0,
        sourceConfidence: 1,
      };
    }

    const correctIndexes = Array.isArray(template.correct)
      ? template.correct
      : [template.correct ?? 0];
    const { options, correctIndexes: rotatedCorrectIndexes } = rotateOptions(
      template.options ?? [],
      correctIndexes,
      seed + index,
    );
    const correctOptionIds = rotatedCorrectIndexes.map((optionIndex) => OPTION_IDS[optionIndex]);

    return {
      questionNumber: startNumber + index,
      text: template.text,
      options,
      correctOptionId: correctOptionIds[0],
      correctOptionIds,
      correctNumericalAnswer: null,
      numericalTolerance: null,
      type: template.kind === "msq" ? "MULTI_CHOICE" : "SINGLE_CHOICE",
      explanation: template.explanation,
      subjectTag: sectionName,
      topicTag: template.topic,
      marks: questionMarksValue,
      negativeMarks:
        template.kind === "msq"
          ? 0
          : questionMarksValue >= 2
            ? Math.max(negativeMarks, 2 / 3)
            : Math.max(negativeMarks, 1 / 3),
      sourceConfidence: 1,
    };
  });
}
